import {readFile} from 'node:fs/promises';
import path from 'node:path';

const json = value => JSON.stringify(value, null, 2) + '\n';

/** Compile the recipe into a native DSH profile bundle; paths are relative to dist/dsh. */
export async function render({root, meta, texts}) {
  const generated = `# Generated by adapters/dsh/build.mjs from recipe/. Edit recipe/, then rebuild.\n`;
  return new Map([
    ['LICENSE', await readFile(path.join(root, 'LICENSE'), 'utf8')],
    ['index.mjs', await readFile(new URL('./runtime.mjs', import.meta.url), 'utf8')],
    ['texts.json', json(texts)],
    ['package.json', json({
      name: 'dsh-gpt-with-taste',
      version: meta.version,
      description: `${meta.name}: ${meta.description}`,
      license: 'MIT',
      type: 'module',
      main: './index.mjs',
      exports: {'.': './index.mjs', './cordis.patch.yml': './cordis.patch.yml'},
      files: ['index.mjs', 'texts.json', 'cordis.patch.yml', 'LICENSE'],
      engines: {node: '^22.19.0 || >=24.0.0'},
      peerDependencies: {'@deepseek-ai/dsh-llm': '>=0.1.0-rc.6 <0.3.0'},
      dsh: {bundle: {patch: './cordis.patch.yml'}},
    })],
    ['cordis.patch.yml', `${generated}- insert:\n    - id: gpt-with-taste\n      name: dsh-gpt-with-taste\n      config:\n        rootRole: main\n`],
  ]);
}
